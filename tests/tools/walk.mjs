// Walk the built site and screenshot every section: node tests/tools/walk.mjs <url> [width] [height] [tag]
// Screenshots land in $SHOT_DIR (default ./shots). Prints page errors and failed requests.
import { chromium } from 'playwright';
const out = process.env.SHOT_DIR || 'shots';
const base = process.argv[2] || 'http://localhost:4181/';
const w = +(process.argv[3] || 1440), h = +(process.argv[4] || 900);
const tag = process.argv[5] || 'd';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: w, height: h }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => ['error', 'warning'].includes(m.type()) && errors.push(m.type() + ': ' + m.text()));
page.on('response', (r) => r.status() >= 400 && errors.push(r.status() + ' ' + r.url()));
await page.goto(base, { waitUntil: 'load' });
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/${tag}-hero.png` });
const shot = async (name, fn, wait = 1800) => { await fn(); await page.waitForTimeout(wait); await page.screenshot({ path: `${out}/${tag}-${name}.png` }); };
const go = (hash) => () => page.evaluate((h) => (location.hash = h), hash);
await shot('map', go('#/community'), 2200);
await shot('map-pick', () => page.click('.place-item[data-place="saint-denis"]'), 1200);
for (const t of ['care', 'discovery', 'opportunity', 'community', 'resources']) await shot(`pillar-${t}`, go(`#/chapter/${t}`), 2200);
await shot('progress', go('#/progress'), 2400);
await shot('measures', () => page.evaluate(() => { const el = document.querySelector('.measures'); scrollTo(0, el.getBoundingClientRect().top + scrollY - 80); }), 2400);
await shot('promises', go('#/promises'), 2200);
await shot('people', go('#/people'), 2200);
await shot('library', go('#/share'), 2200);
await shot('training', go('#/training'), 2200);
await shot('sources', go('#/sources'), 2200);
await shot('story', go('#/story/pa10-heat'), 1500);
console.log(JSON.stringify({ st: await page.evaluate(() => window.__impact.store.get()) }));
console.log(errors.join('\n') || 'no errors');
await browser.close();

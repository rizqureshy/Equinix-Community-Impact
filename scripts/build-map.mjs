// Builds the dot-matrix world map used by the impact explorer.
// Samples a regular grid of longitude/latitude points and keeps the ones on
// land, writing them to impact/scripts/content/map-dots.js so the page never
// loads geographic data at runtime. Run after changing STEP or the bounds.
//   node scripts/build-map.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-110m.json', import.meta.url)));
const land = feature(topo, topo.objects.land);
const STEP = 1.5; // degrees between dots
const LAT = [-55, 72]; // drop Antarctica, keep Scandinavia

const rings = [];
for (const f of land.features) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) for (const ring of poly) rings.push(ring);
}
const inside = (x, y) => {
  let hit = false;
  for (const ring of rings) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
    }
  }
  return hit;
};

const dots = [];
for (let lat = LAT[1]; lat >= LAT[0]; lat -= STEP) {
  for (let lon = -180; lon < 180; lon += STEP) {
    if (inside(lon + 0.01, lat + 0.01)) dots.push([+lon.toFixed(1), +lat.toFixed(1)]);
  }
}
const out = `// Generated by scripts/build-map.mjs from world-atlas land-110m (Natural Earth, public domain).\n// Land as [longitude, latitude] dots on a ${STEP} degree grid, latitude ${LAT[0]} to ${LAT[1]}.\nexport const STEP = ${STEP};\nexport const LAT_RANGE = [${LAT[0]}, ${LAT[1]}];\nexport const DOTS = ${JSON.stringify(dots)};\n`;
writeFileSync(new URL('../impact/scripts/content/map-dots.js', import.meta.url), out);
console.log(`${dots.length} land dots written`);
